def remove_codex_hooks():
    """Takes orcha's stage hook out of ~/.codex/hooks.json, keeping the rest."""
    try:
        with open(CODEX_HOOKS) as fh:
            data = json.load(fh)
    except (OSError, ValueError):
        return
    hooks = data.get("hooks", {})
    for event in list(hooks):
        hooks[event] = [g for g in hooks[event]
                        if not any("/claude/hooks/orcha-" in h.get("command", "") for h in g.get("hooks", []))]
        if not hooks[event]:
            del hooks[event]
    if not hooks and set(data) <= {"hooks"} and not os.path.exists(CODEX_HOOKS + ".pre-orcha"):
        os.remove(CODEX_HOOKS)  # orcha made it: nothing else in it
        return
    write(CODEX_HOOKS, json.dumps(data, indent=2, ensure_ascii=False) + "\n")


def claude_theme(on):
    """Claude Code in orcha's colors: its "dark-ansi" theme draws with the
    terminal's 16 colors, which are the palette's. The theme it had before is
    kept in gen/claude-theme and put back when the widget goes off."""
    try:
        with open(CLAUDE_SETTINGS) as fh:
            settings = json.load(fh)
    except FileNotFoundError:
        settings = {}
    except ValueError:
        return None
    saved = os.path.join(o.GEN_DIR, "claude-theme")
    cur = settings.get("theme")
    if on and cur != "dark-ansi":
        write(saved, json.dumps(cur))
        settings["theme"] = "dark-ansi"
    elif not on and cur == "dark-ansi" and os.path.exists(saved):
        with open(saved) as fh:
            old = json.load(fh)
        if old is None:
            settings.pop("theme", None)
        else:
            settings["theme"] = old
        os.remove(saved)
    else:
        return None
    write(CLAUDE_SETTINGS, json.dumps(settings, indent=2, ensure_ascii=False) + "\n")
    return None


