"""`orcha apply`: write every app's config from ~/.config/orcha/config.json.

What it writes (and nothing else):
  ~/.config/orcha/gen/env.sh                  settings, colors, strings for the scripts
  ~/.config/ghostty/themes/orcha              the palette as a Ghostty theme
  ~/.config/ghostty/orcha.ghostty             font, window, shortcuts, shader, logos
  ~/.config/ghostty/shaders/orcha-trail.glsl  the cursor trail, in your accent
  + one `config-file = ...orcha.ghostty` line at the end of your Ghostty config
  ~/.config/herdr/config.toml                 (yours is kept as config.toml.pre-orcha;
                                               add your own lines in ~/.config/orcha/herdr.extra.toml)
  ~/.config/herdr/sounds/orcha-*.mp3          when the sounds widget is on
  ~/.claude/settings.json                     the guard and check hooks (merged in, marked "orcha")
"""
