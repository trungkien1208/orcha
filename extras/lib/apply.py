def link_ghostty_main():
    """Add `config-file = <orcha.ghostty>` to the end of your Ghostty config."""
    main = next((f for f in GHOSTTY_MAIN if os.path.exists(f)), None)
    if not main:
        main = GHOSTTY_MAIN[0] if os.path.isdir(os.path.dirname(GHOSTTY_MAIN[0])) else GHOSTTY_MAIN[3]
        write(main, "")
    target = os.path.join(GHOSTTY_DIR, "orcha.ghostty")
    with open(main) as fh:
        text = fh.read()
    if target in text:
        return main
    if not os.path.exists(main + ".pre-orcha"):
        shutil.copy2(main, main + ".pre-orcha")
    sep = "" if text.endswith("\n") or not text else "\n"
    with open(main, "a") as fh:
        fh.write(f"{sep}\n{MARK}: its theme, font and shortcuts (remove these 2 lines to turn orcha off)\n"
                 f"config-file = {target}\n")
    return main


def shader(p):
    with open(os.path.join(o.ORCHA_HOME, "ghostty", "cursor-trail.glsl.in")) as fh:
        text = fh.read()
    r, g, b = (c / 255 for c in o.rgb(p["accent"]))
    return text.replace("{{TRAIL_RGB}}", f"{r:.3f}, {g:.3f}, {b:.3f}").replace("{{TRAIL_HEX}}", p["accent"])


# ---------- herdr

def herdr_conf(cfg, p, t):
    w = cfg["widgets"]
    S = os.path.join(o.ORCHA_HOME, "scripts")
    tc = lambda k: f'{k} = "{p[k]}"'  # noqa: E731
    native = p.get("native")  # the "default" palette: herdr keeps its own colors
    fgc = lambda c: {} if native else {"fg": c}  # noqa: E731
    out = [
        "# generated by `orcha apply`: edits here are overwritten.",
        "# Your own settings: ~/.config/orcha/herdr.extra.toml (appended below).",
        "onboarding = false", "",
    ]
    if native:
        # herdr's "terminal" theme draws with the terminal's own colors, so
        # herdr matches whatever theme Ghostty has
        out += ["[theme]", 'name = "terminal"', "auto_switch = false", ""]
    else:
        out += [
        "[theme]", f'name = "{p.get("herdr_base", "catppuccin")}"', "auto_switch = false", "",
        "[theme.custom]",
        f'accent = "{p["accent"]}"', 'panel_bg = "reset"',
        tc("sidebar_bg"), tc("active_row_bg"), f'selection_bg = "{p["selection_bg"]}"',
        tc("surface0"), tc("surface1"), f'surface_dim = "{p["sidebar_bg"]}"',
        tc("overlay0"), tc("overlay1"), f'text = "{p["fg"]}"', tc("subtext0"),
        f'mauve = "{p["magenta"]}"', tc("red"), tc("green"), tc("yellow"), tc("blue"),
        f'teal = "{p["cyan"]}"', tc("peach"), ""]
    out += [
        "[ui]",
        'status_indicators = "dots"',
        "" if native else f'accent = "{p["accent"]}"',
        'agent_panel_sort = "spaces"',
        'pane_borders = "always"', "pane_outer_borders = true", "pane_gaps = true",
        "show_agent_labels_on_pane_borders = true",
        'tab_bar_position = "top"', 'tab_bar_right_separator = "  ·  "',
        "tab_bar_right = [",
        '  { type = "zoom" },',
        # tab-names.py also feeds the sidebar tokens, so it runs even with tab names off
        f'  {{ type = "command", command = {toml_str(S + "/tab-names.py")}, interval_seconds = 3, timeout_seconds = 15 }},',
    ]
    if any(w[k] for k in ("task", "changes", "pomodoro", "limits", "weather", "recap")):
        out.append(f'  {{ type = "command", command = {toml_str(S + "/header.sh")}, interval_seconds = 2, timeout_seconds = 20 }},')
    if w["clock"]:
        out.append('  { type = "datetime", format = "%H:%M" },')
    out += ["]", ""]

    name = {"token": "agent", "bold": True}
    state = {"token": "state_text", **fgc(p["muted"])}
    task = {"token": "$task", **fgc(p["dim"])}
    row = lambda color: ["state_icon", dict(name, **fgc(color)), state, task]  # noqa: E731
    group = [{"token": "$grp", **fgc(p["accent"]), "bold": True}]

    def rows_toml(rows):
        def cell(c):
            if isinstance(c, str):
                return toml_str(c)
            return "{ " + ", ".join(f"{k} = {toml_str(v) if isinstance(v, str) else str(v).lower()}"
                                    for k, v in c.items()) + " }"
        return "[\n" + "".join("  [" + ", ".join(cell(c) for c in r) + "],\n" for r in rows) + "]"

    out += ["[ui.sidebar.spaces]", "# projects, with how many agents run in each ($count from tab-names.py)",
            "row_gap = 1",
            "rows = " + rows_toml([["state_icon", {"token": "workspace", **fgc(p["fg"]), "bold": True},
                                    {"token": "$count", **fgc(p["accent"])}]]), ""]
    agent_colors = {} if native else {"claude": p["peach"], "codex": p["green"], "cursor": p["blue"]}
    if w["sidebar_groups"]:
        out += ["[ui.sidebar.agents]",
                "# agents grouped by project: $grp is the project's name on its first agent,",
                "# $task the chat title (both from tab-names.py)",
                "row_gap = 0", "rows = " + rows_toml([group, row(p["accent"])]), "",
                "[ui.sidebar.agents.rows_by_agent]"]
        for a, c in agent_colors.items():
            out.append(f"{a} = " + rows_toml([group, row(c)]))
    else:
        out += ["[ui.sidebar.agents]", "row_gap = 1", "rows = " + rows_toml([row(p["accent"])]), "",
                "[ui.sidebar.agents.rows_by_agent]"]
        for a, c in agent_colors.items():
            out.append(f"{a} = " + rows_toml([row(c)]))
    out += ["", "[ui.toast]", 'delivery = "herdr"', ""]

    if w["sounds"]:
        out += ["[ui.sound]", "enabled = true",
                'done_path = "sounds/orcha-done.mp3"', 'request_path = "sounds/orcha-request.mp3"', ""]

    for _gkey, hkey, script, popup, width, height, desc in KEYS:
        if hkey == "m" and cfg["git_app"] == "none":
            continue
        if hkey == "u" and not (cfg["accounts"] and w["limits"]):
            continue
        cmd = 'cd "${HERDR_ACTIVE_PANE_CWD:-$HOME}" && exec yazi' if script is None else f"{S}/{script}"
        out += ["[[keys.command]]", f'key = "prefix+{hkey}"', f'type = "{"popup" if popup else "shell"}"',
                f"command = {toml_str(cmd)}", f"description = {toml_str(t[desc])}"]
        if popup:
            out += [f'width = "{width}"', f'height = "{height}"']
        out.append("")

    extra = os.path.join(o.CONFIG_DIR, "herdr.extra.toml")
    if os.path.exists(extra):
        with open(extra) as fh:
            out += ["# ---- from ~/.config/orcha/herdr.extra.toml", fh.read()]
    return "\n".join(out) + "\n"


def sounds():
    """Glass (done) and Purr (needs you) from macOS, as mp3 (herdr plays mp3 only)."""
    if not shutil.which("lame"):
        return "lame missing (brew install lame): sounds off"
    d = os.path.join(HERDR_DIR, "sounds")
    os.makedirs(d, exist_ok=True)
    for name, src in (("done", "Glass"), ("request", "Purr")):
        dst = os.path.join(d, f"orcha-{name}.mp3")
        if os.path.exists(dst):
            continue
        with tempfile.TemporaryDirectory() as tmp:
            wav = os.path.join(tmp, "s.wav")
            subprocess.run(["afconvert", "-f", "WAVE", "-d", "LEI16", f"/System/Library/Sounds/{src}.aiff", wav],
                           capture_output=True, check=False)
            subprocess.run(["lame", "--silent", "-b", "128", wav, dst], capture_output=True, check=False)
    return None


# ---------- Claude Code hooks

def claude_hooks():
    """Merge the guard and check hooks into ~/.claude/settings.json (user scope:
    every repo; each repo's rules decide what they do there)."""
    if not os.path.isdir(os.path.join(o.HOME, ".claude")):
        return "no ~/.claude: Claude Code hooks skipped"
    H = os.path.join(o.ORCHA_HOME, "claude", "hooks")
    want = {
        "PreToolUse": [("Bash|Edit|Write|MultiEdit|NotebookEdit", f"{H}/orcha-guard.sh pre", None)],
        "PostToolUse": [("Edit|Write|MultiEdit|NotebookEdit", f"{H}/orcha-check.sh mark", None),
                        ("Bash|Edit|Write|MultiEdit|NotebookEdit", f"{H}/orcha-guard.sh post", None)],
        "Stop": [(None, f"{H}/orcha-check.sh stop", 300)],
        # the station of the agent's train in the orcha sidebar
        "UserPromptSubmit": [(None, f"{H}/orcha-stage.sh", 5)],
        # the train's name: the model the session runs
        "SessionStart": [(None, f"{H}/orcha-stage.sh", 5)],
    }
    want["PreToolUse"].append(("*", f"{H}/orcha-stage.sh", 5))
    try:
        with open(CLAUDE_SETTINGS) as fh:
            settings = json.load(fh)
    except FileNotFoundError:
        settings = {}
    except ValueError:
        return "~/.claude/settings.json is not valid JSON: hooks skipped"
    if not os.path.exists(CLAUDE_SETTINGS + ".pre-orcha") and os.path.exists(CLAUDE_SETTINGS):
        shutil.copy2(CLAUDE_SETTINGS, CLAUDE_SETTINGS + ".pre-orcha")
    hooks = settings.setdefault("hooks", {})
    for event, entries in want.items():
        # drop orcha's old entries (any install path), then add the current ones
        kept = [g for g in hooks.get(event, [])
                if not any("/claude/hooks/orcha-" in h.get("command", "") for h in g.get("hooks", []))]
        for matcher, command, timeout in entries:
            hook = {"type": "command", "command": command}
            if timeout:
                hook["timeout"] = timeout
            group = {"hooks": [hook]}
            if matcher:
                group = {"matcher": matcher, **group}
            kept.append(group)
        hooks[event] = kept
    write(CLAUDE_SETTINGS, json.dumps(settings, indent=2, ensure_ascii=False) + "\n")
    return None


