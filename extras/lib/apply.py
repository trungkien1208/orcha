def write(path, text, mode=0o644):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path))
    with os.fdopen(fd, "w") as fh:
        fh.write(text)
    os.chmod(tmp, mode)
    os.replace(tmp, path)


def sh_quote(s):
    return "'" + str(s).replace("'", "'\\''") + "'"


def toml_str(s):
    return json.dumps(str(s), ensure_ascii=False)


# ---------- env.sh for the shell scripts

def env_sh(cfg, p, t):
    w = cfg["widgets"]
    lines = ["# generated by `orcha apply` from config.json: edits here are overwritten"]
    settings = {
        "ORCHA_HOME": o.ORCHA_HOME,
        "ORCHA_CONFIG_DIR": o.CONFIG_DIR,
        "ORCHA_CACHE": o.CACHE,
        "ORCHA_LANG": cfg["lang"],
        "O_IDE": cfg["ide"],
        "O_IDE_APP": cfg.get("ide_app") or o.IDES.get(cfg["ide"], ("", ""))[1],
        "O_GIT_APP": cfg["git_app"],
        "O_GIT_APP_NAME": o.GIT_APPS.get(cfg["git_app"], ("", ""))[1],
        "O_PROTECTED": cfg["repo"]["protected"],
        "O_WEATHER_CITY": cfg.get("weather_city", ""),
        "O_HAS_ACCOUNTS": "1" if cfg["accounts"] and w["limits"] else "",
    }
    for k, v in settings.items():
        lines.append(f"{k}={sh_quote(v)}")
    for k in o.WIDGETS:
        lines.append(f"W_{k}={1 if w.get(k) else 0}")
    for k in ("bg", "fg", "accent", "muted", "dim", "red", "green", "yellow", "blue", "magenta", "cyan",
              "peach", "subtext0", "overlay1", "surface1", "selection_bg", "active_row_bg"):
        r, g, b = o.rgb(p[k])
        lines.append(f"C_{k}={sh_quote(p[k])}; R_{k}='{r};{g};{b}'")
    for k, v in t.items():
        if isinstance(v, str):
            lines.append(f"T_{k}={sh_quote(v)}")
    colors = "" if p.get("native") else (
        f"--color=bg:{p['bg']},bg+:{p['active_row_bg']},fg:{p['subtext0']},fg+:{p['fg']},"
        f"hl:{p['accent']},hl+:{p['red']} "
        f"--color=prompt:{p['accent']},pointer:{p['red']},marker:{p['green']},info:{p['overlay1']},"
        f"border:{p['dim']},header:{p['blue']},gutter:{p['bg']} "
        f"--color=footer:{p['red']},footer-border:{p['dim']} ")
    fzf = (f"--layout=reverse --border=rounded --info=inline-right --pointer='▌' --marker='+' {colors}"
           # herdr popups have no close mark of their own: a popup closes when fzf exits
           f"--footer='  ✕  {t['close']}   ({t['close_hint']})' --footer-border=top --bind=click-footer:abort")
    lines.append(f"export FZF_DEFAULT_OPTS={sh_quote(fzf)}")
    lines.append("export BAT_THEME=ansi")
    return "\n".join(lines) + "\n"


# ---------- plugin.json for the Claude Code plugin

def plugin_json(cfg, p, t):
    """What the orcha Claude plugin reads: where orcha lives, colors, strings, rules."""
    return json.dumps({
        "home": o.ORCHA_HOME,
        "cache": o.CACHE,
        "colors": {k: p[k] for k in ("accent", "red", "green", "blue", "yellow", "magenta", "muted", "fg", "peach")},
        "strings": {k: v for k, v in t.items() if k.startswith(("m_", "st_"))},
        "repo": cfg["repo"],
        "widgets": cfg["widgets"],
    }, indent=1, ensure_ascii=False) + "\n"


